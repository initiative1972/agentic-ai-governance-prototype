"""Agentic AI Assurance Report generator (NIST AI RMF structure).

Summarises the agent inventory (GOVERN), the applicable OWASP agentic threats
(MAP), the governed-action ledger (MEASURE) and the kill-switch events (MANAGE),
with a decision + sign-off block — the artefact a governance forum reviews.
"""
from __future__ import annotations

import time
from collections import Counter
from typing import List

from .attestation import AuditLedger
from .breaker import CircuitBreaker
from .identity import AgentRegistry
from .owasp_agentic import AGENTIC_TOP_10


def render_assurance_report(registry: AgentRegistry, ledger: AuditLedger,
                            breaker: CircuitBreaker, applicable_threats: List[str],
                            system_name: str = "Enterprise Multi-Agent System",
                            version: str = "pilot-v1", owner: str = "Henry Yan") -> str:
    decisions = Counter(r.decision for r in ledger.records)
    high = [r for r in ledger.records if r.band in ("High", "Critical")]
    blocked = any(r.decision in ("DENY", "HALT") for r in ledger.records)
    contained = breaker.system.tripped or any(s.tripped for s in breaker.agents.values())
    status = "REVIEW REQUIRED" if (blocked or contained) else "PASS"

    L: List[str] = []
    L.append(f"# Agentic AI Assurance Report - {system_name}\n")
    L.append(f"> **Assurance status: {status}** - Generated {time.strftime('%Y-%m-%d %H:%M')} - Prototype v0.1.0\n")

    L.append("## 1. System & agents (GOVERN)")
    L.append(f"- **System / version:** {system_name} {version}")
    L.append(f"- **Owner / accountable:** {owner}")
    L.append(f"- **Ledger integrity (hash-chain + attestation verified):** {'PASS' if ledger.verify() else 'FAIL'}\n")
    L.append("| Agent | Role | Trust tier | Clearance | Capabilities |")
    L.append("| --- | --- | --- | --- | --- |")
    for a in registry.all():
        caps = ", ".join(a.capabilities) or "-"
        L.append(f"| {a.agent_id} | {a.role} | {a.trust_tier.name} | {a.clearance} | {caps} |")

    L.append("\n## 2. Threat model (MAP) - OWASP Top 10 for Agentic Applications")
    L.append("| ID | Threat | Key controls |")
    L.append("| --- | --- | --- |")
    for tid in applicable_threats:
        t = AGENTIC_TOP_10[tid]
        L.append(f"| {t.id} | {t.title} | {'; '.join(t.controls)} |")

    L.append("\n## 3. Governed-action ledger (MEASURE)")
    L.append(f"- Total actions governed: {len(ledger.records)}")
    for d, c in decisions.most_common():
        L.append(f"- {d}: {c}")
    L.append(f"- High/Critical actions: {len(high)}\n")
    L.append("| Seq | Agent | Action | Inherent | Band | Decision |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    for r in ledger.records:
        L.append(f"| {r.seq} | {r.agent_id} | {r.action} | {r.inherent} | {r.band} | {r.decision} |")

    L.append("\n## 4. Kill-switch & containment (MANAGE)")
    if breaker.log:
        for e in breaker.log:
            L.append(f"- {e}")
    else:
        L.append("- No breaker events; no containment required.")

    L.append("\n## 5. Limitations")
    L.append("- Prototype on a synthetic multi-agent scenario; risk weights and thresholds are "
             "illustrative and must be agreed with Risk & Compliance per use case.")
    L.append("- The gateway is a decision point advisory to a human governance forum; integrate with "
             "`microsoft/agent-governance-toolkit` for production-grade runtime enforcement.")
    L.append("- OWASP Agentic identifiers reflect the 2026 list - verify against the current publication.")

    L.append("\n## 6. Governance decision")
    rec = ("NOT APPROVED - remediate blocked/halted actions and re-run"
           if status != "PASS" else "APPROVED within stated guardrails")
    L.append(f"- **Recommendation:** {rec}")
    L.append("- **Reviewed by (AI / Technology Risk - 2LoA):** ____________________  Date: __________")
    L.append("- **Endorsed by (accountable owner):** ____________________  Date: __________")
    L.append("\n---")
    L.append("*Generated by the Agentic AI Governance Prototype. Built on the concepts in "
             "microsoft/agent-governance-toolkit; complements the Responsible AI Evaluation Harness.*")
    return "\n".join(L)
